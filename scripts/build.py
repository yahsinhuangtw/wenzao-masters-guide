#!/usr/bin/env python3
"""Build the derived files of the Wenzao master's guide. Standard library only.

    python3 scripts/build.py

Reads   data/calendar-115.json         (single source of truth for dates)
Writes  reference/calendar-115.md      (table the AI reads)
        dist/wenzao-115-masters.ics    (calendar file students import)
        dist/wenzao-masters-guide-bundle.md  (everything in one file for AIs
                                              that can't load a folder)
"""
import datetime as dt
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LEVELS = {"dont_miss": "Don't miss", "check": "Check", "info": "Info"}
BUNDLE_ORDER = [
    "SKILL.md",
    "reference/calendar-115.md",
    "reference/lifecycle-timeline.md",
    "reference/course-selection.md",
    "reference/thesis-and-advisor.md",
    "reference/research-and-library.md",
    "reference/departments/gies.md",
    "reference/departments/dia.md",
    "reference/sources.md",
    "templates/thesis-topic-worksheet.md",
    "templates/advisor-email.md",
    "templates/advisor-meeting-agenda.md",
    "templates/office-email-missed-selection.md",
]


def load_events():
    data = json.loads((ROOT / "data" / "calendar-115.json").read_text(encoding="utf-8"))
    seen = set()
    for e in data["events"]:
        if e["id"] in seen:
            sys.exit(f"duplicate id: {e['id']}")
        seen.add(e["id"])
        e["_start"] = dt.date.fromisoformat(e["start"])
        e["_end"] = dt.date.fromisoformat(e["end"])
        if e["_end"] < e["_start"]:
            sys.exit(f"end before start: {e['id']}")
        if e["level"] not in LEVELS:
            sys.exit(f"bad level: {e['id']}")
    data["events"].sort(key=lambda e: (e["_start"], e["_end"]))
    return data


def date_range(e):
    if e["_start"] == e["_end"]:
        return e["start"]
    return f"{e['start']} to {e['end']}"


def build_markdown(data):
    lines = [
        "# Academic calendar 2026-27 (115 academic year)",
        "",
        "<!-- Generated by scripts/build.py from data/calendar-115.json. Do not edit by hand. -->",
        "",
        f"Source: {data['source']}, approved {data['approved']}. Extracted {data['extracted']}.",
        f"Division: {data['division']}. {data['note']}",
        "",
        "Levels: **Don't miss** = missing it has real consequences, push it. **Check** = may apply, ask the student. **Info** = background.",
        "",
        "Status: read from the official PDF by text extraction, not yet checked against the PDF by a person. Public holidays are left out.",
        "",
    ]
    for term, title in (("115-1", "Semester 1 (2026-08-01 to 2027-01-31)"), ("115-2", "Semester 2 (2027-02-01 to 2027-07-31)")):
        lines += [f"## {title}", "", "| Dates | Event | 中文 | Level |", "|---|---|---|---|"]
        for e in data["events"]:
            if e["term"] == term:
                lines.append(f"| {date_range(e)} | {e['en']} | {e['zh']} | {LEVELS[e['level']]} |")
        lines.append("")
    lines += [
        "## Two things this calendar does not tell you",
        "",
        "- Which windows apply to master's students and what the exact procedure is. `TODO(verify)` with the Academic Affairs Office (教務處) and the department office.",
        "- The first-round selection for returning students for semester 1 of this year: it happened in the previous year's calendar, which this file does not include.",
        "",
    ]
    (ROOT / "reference" / "calendar-115.md").write_text("\n".join(lines), encoding="utf-8")


def ics_escape(text):
    return text.replace("\\", "\\\\").replace(";", "\\;").replace(",", "\\,").replace("\n", "\\n")


def fold(line):
    """RFC 5545: lines are at most 75 octets; continuations start with a space."""
    b = line.encode("utf-8")
    out, limit = [], 75
    while len(b) > limit:
        cut = limit
        while (b[cut] & 0xC0) == 0x80:
            cut -= 1
        out.append(b[:cut].decode("utf-8"))
        b = b[cut:]
        limit = 74
    out.append(b.decode("utf-8"))
    return "\r\n ".join(out)


def build_ics(data):
    now = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    lines = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//wenzao-masters-guide//EN",
        "CALSCALE:GREGORIAN",
        "METHOD:PUBLISH",
        "X-WR-CALNAME:Wenzao 2026-27 key dates",
        "X-WR-TIMEZONE:Asia/Taipei",
    ]
    for e in data["events"]:
        prefix = "[!] " if e["level"] == "dont_miss" else ""
        desc = (
            f"{e['zh']}\n"
            f"Source: {data['source']}, approved {data['approved']}. "
            "Confirm with the Academic Affairs Office; the calendar can be revised."
        )
        lines += [
            "BEGIN:VEVENT",
            f"UID:{e['id']}@wenzao-masters-guide",
            f"DTSTAMP:{now}",
            f"DTSTART;VALUE=DATE:{e['_start']:%Y%m%d}",
            f"DTEND;VALUE=DATE:{(e['_end'] + dt.timedelta(days=1)):%Y%m%d}",
            f"SUMMARY:{ics_escape(prefix + e['en'])}",
            f"DESCRIPTION:{ics_escape(desc)}",
            f"CATEGORIES:{e['cat']}",
        ]
        if e["level"] == "dont_miss":
            for trigger in ("-P7D", "-P1D"):
                lines += [
                    "BEGIN:VALARM",
                    "ACTION:DISPLAY",
                    f"DESCRIPTION:{ics_escape(e['en'])}",
                    f"TRIGGER:{trigger}",
                    "END:VALARM",
                ]
        lines.append("END:VEVENT")
    lines.append("END:VCALENDAR")
    (ROOT / "dist" / "wenzao-115-masters.ics").write_bytes(
        ("\r\n".join(fold(l) for l in lines) + "\r\n").encode("utf-8")
    )


def build_bundle():
    parts = [
        "# Wenzao master's guide: single-file bundle",
        "",
        "Generated by scripts/build.py. Load this whole file as the AI's instructions or knowledge. "
        "Inside, `SKILL.md` refers to files by path such as `reference/calendar-115.md`: those files are included below under the same headings. "
        "The calendar file is `dist/wenzao-115-masters.ics` (not included here; give it to the student separately).",
        "",
    ]
    for rel in BUNDLE_ORDER:
        path = ROOT / rel
        if not path.exists():
            sys.exit(f"missing file for bundle: {rel}")
        parts += ["", "=" * 70, f"FILE: {rel}", "=" * 70, "", path.read_text(encoding="utf-8").strip(), ""]
    (ROOT / "dist" / "wenzao-masters-guide-bundle.md").write_text("\n".join(parts), encoding="utf-8")


def count_todos():
    n = 0
    for rel in BUNDLE_ORDER:
        n += len(re.findall(r"TODO\(verify\)", (ROOT / rel).read_text(encoding="utf-8")))
    return n


def main():
    data = load_events()
    build_markdown(data)
    build_ics(data)
    build_bundle()
    print(f"events: {len(data['events'])}")
    print(f"TODO(verify) markers still open: {count_todos()}")
    print("wrote reference/calendar-115.md, dist/wenzao-115-masters.ics, dist/wenzao-masters-guide-bundle.md")


if __name__ == "__main__":
    main()
