#!/usr/bin/env python3
"""Generate the human-readable question list and a blank scoring sheet from evals.json.

    python3 evals/make_sheet.py
    python3 evals/make_sheet.py --assistants "Claude,ChatGPT,Gemini" --shuffle-seed 1

Writes  evals/questions.md   (questions with their specific checks)
        evals/run-sheet.csv  (one row per assistant x arm x question, scores blank)
Standard library only.
"""
import argparse
import csv
import json
import pathlib
import random

HERE = pathlib.Path(__file__).resolve().parent
ARMS = ["with_guide", "without_guide"]
SCORE_COLS = ["F1", "F2", "F3", "F4", "F5", "F6", "helpful_1to5"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--assistants", default="Claude,ChatGPT,Gemini")
    ap.add_argument("--shuffle-seed", type=int, default=None,
                    help="shuffle row order so the scorer is less likely to see the arm pattern")
    args = ap.parse_args()

    data = json.loads((HERE / "evals.json").read_text(encoding="utf-8"))
    evals = data["evals"]

    lines = [
        "# Evaluation questions",
        "",
        "<!-- Generated by evals/make_sheet.py from evals/evals.json. Do not edit by hand. -->",
        "",
        f"{len(evals)} questions. Run each one in a fresh conversation, with the guide loaded and without it. "
        "Score with `rubric.md`.",
        "",
    ]
    for e in evals:
        lines += [
            f"## {e['id']}. {e['name']}  ({e['category']})",
            "",
            f"> {e['prompt']}",
            "",
            f"Good answer: {e['expected_output']}",
            "",
            "Specific checks:",
            *[f"- {x}" for x in e["expectations"]],
            "",
        ]
    (HERE / "questions.md").write_text("\n".join(lines), encoding="utf-8")

    rows = [
        {"assistant": a.strip(), "arm": arm, "eval_id": e["id"], "eval_name": e["name"]}
        for a in args.assistants.split(",") if a.strip()
        for arm in ARMS
        for e in evals
    ]
    if args.shuffle_seed is not None:
        random.Random(args.shuffle_seed).shuffle(rows)
    with open(HERE / "run-sheet.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["assistant", "arm", "eval_id", "eval_name"] + SCORE_COLS + ["notes"])
        w.writeheader()
        for r in rows:
            w.writerow({**r, **{c: "" for c in SCORE_COLS}, "notes": ""})
    print(f"{len(evals)} questions, {len(rows)} rows -> evals/questions.md, evals/run-sheet.csv")


if __name__ == "__main__":
    main()
